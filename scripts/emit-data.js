const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const { data, defaults } = JSON.parse(fs.readFileSync(path.join(root, 'replacecover/rebuild-data.json'), 'utf8'));

const outDir = path.join(root, 'rebuild/src/data');
fs.mkdirSync(outDir, { recursive: true });

const banner = '// Generated by scripts/emit-data.mjs from the shipped artifact.\n';
const write = (name, decl) => fs.writeFileSync(path.join(outDir, name), banner + decl + '\n');

write('themes.js', `export const themes = ${JSON.stringify(data.themes, null, 2)};`);
write('things.js', `export const things = ${JSON.stringify(data.things, null, 2)};`);
write('playlistNames.js', `export const randomPlaylistNames = ${JSON.stringify(data.randomPlaylistNames, null, 2)};`);
write('defaults.js', `// Verbatim from the shipped default consts c,s,u,m,d - including the\n// original's own disagreements with the tables (see docs/quirks.md).\nexport const defaultTheme = ${JSON.stringify(defaults.activeTheme)};\nexport const defaultThing = ${JSON.stringify(defaults.activeThing)};\nexport const defaultCopy = ${JSON.stringify(defaults.activeCopy)};\nexport const defaultTextSize = ${JSON.stringify(defaults.textSize)};\nexport const defaultTextAlignment = ${JSON.stringify(defaults.textAlignment)};\n`);

// Round-trip check: the emitted ESM must parse back to the same tables.
const reload = (f) => {
  const txt = fs.readFileSync(path.join(outDir, f), 'utf8');
  const json = txt.slice(txt.indexOf('[') >= 0 ? txt.indexOf('=') + 1 : txt.indexOf('=') + 1).trim().replace(/;$/, '');
  return JSON.parse(json);
};
const checks = [
  ['themes.js', data.themes],
  ['things.js', data.things],
  ['playlistNames.js', data.randomPlaylistNames],
];
for (const [f, expected] of checks) {
  const got = reload(f);
  if (JSON.stringify(got) !== JSON.stringify(expected)) throw new Error('round-trip mismatch: ' + f);
  console.log('round-trip OK', f, got.length, 'rows');
}
console.log('emitted', outDir);
